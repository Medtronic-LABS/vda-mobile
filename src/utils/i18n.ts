// Localized helper functions for FHIR data
export function getLocalizedField<T extends Record<string, any>>(
  obj: T | undefined | null,
  baseKey: string,
  lang: LanguageCode
): string {
  if (!obj) return '';
  if (lang === 'hi') {
    const hiKey = `${baseKey}Hi`;
    if (obj[hiKey]) return obj[hiKey];
  } else if (lang === 'ta') {
    const taKey = `${baseKey}Ta`;
    if (obj[taKey]) return obj[taKey];
  } else if (lang === 'kn') {
    const knKey = `${baseKey}Kn`;
    if (obj[knKey]) return obj[knKey];
  }
  return obj[baseKey] || '';
}

// Audio Cue Helper
export function playChime(type: 'start' | 'stop' | 'success' | 'alert') {
  try {
    const AudioContextClass = window.AudioContext || (window as any).webkitAudioContext;
    if (!AudioContextClass) return;
    const ctx = new AudioContextClass();
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();
    osc.connect(gain);
    gain.connect(ctx.destination);

    const now = ctx.currentTime;
    if (type === 'start') {
      osc.frequency.setValueAtTime(440, now);
      osc.frequency.exponentialRampToValueAtTime(880, now + 0.15);
      gain.gain.setValueAtTime(0.12, now);
      gain.gain.exponentialRampToValueAtTime(0.01, now + 0.2);
      osc.start(now);
      osc.stop(now + 0.2);
    } else if (type === 'stop') {
      osc.frequency.setValueAtTime(660, now);
      osc.frequency.exponentialRampToValueAtTime(330, now + 0.15);
      gain.gain.setValueAtTime(0.1, now);
      gain.gain.exponentialRampToValueAtTime(0.01, now + 0.2);
      osc.start(now);
      osc.stop(now + 0.2);
    } else if (type === 'alert') {
      osc.type = 'sawtooth';
      osc.frequency.setValueAtTime(800, now);
      osc.frequency.setValueAtTime(600, now + 0.1);
      osc.frequency.setValueAtTime(800, now + 0.2);
      gain.gain.setValueAtTime(0.2, now);
      gain.gain.exponentialRampToValueAtTime(0.01, now + 0.4);
      osc.start(now);
      osc.stop(now + 0.4);
    } else {
      osc.frequency.setValueAtTime(523.25, now);
      osc.frequency.exponentialRampToValueAtTime(659.25, now + 0.1);
      gain.gain.setValueAtTime(0.1, now);
      gain.gain.exponentialRampToValueAtTime(0.01, now + 0.25);
      osc.start(now);
      osc.stop(now + 0.25);
    }
  } catch {
    // ignore audio context restrictions
  }
}

// Text-to-Speech engine
let currentUtterance: SpeechSynthesisUtterance | null = null;

export function speakText(text: string, lang: LanguageCode = 'hi', onEnd?: () => void) {
  if (typeof window === 'undefined' || !('speechSynthesis' in window)) {
    if (onEnd) onEnd();
    return;
  }

  window.speechSynthesis.cancel();

  const utterance = new SpeechSynthesisUtterance(text);
  currentUtterance = utterance;

  const langMap: Record<LanguageCode, string> = {
    hi: 'hi-IN',
    en: 'en-IN',
    ta: 'ta-IN',
    kn: 'kn-IN'
  };
  utterance.lang = langMap[lang] || 'hi-IN';
  utterance.rate = 0.92;
  utterance.pitch = 1.0;

  const voices = window.speechSynthesis.getVoices();
  const match = voices.find(v => v.lang.startsWith(utterance.lang.slice(0, 2)) || v.lang === utterance.lang);
  if (match) {
    utterance.voice = match;
  }

  utterance.onend = () => {
    currentUtterance = null;
    if (onEnd) onEnd();
  };

  utterance.onerror = () => {
    currentUtterance = null;
    if (onEnd) onEnd();
  };

  window.speechSynthesis.speak(utterance);
}

export function stopSpeaking() {
  if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
    window.speechSynthesis.cancel();
    currentUtterance = null;
  }
}
